  var track = document.getElementById("tstiTrack");
  var dotsWrap = document.getElementById("tstiDots");
  var prevBtn = document.getElementById("tstiPrev");
  var nextBtn = document.getElementById("tstiNext");

  function step(){
    var card = track && track.querySelector(".tsti-card");
    if(!card) return 0;
    var style = window.getComputedStyle(track);
    var gap = parseFloat(style.columnGap || style.gap || "0") || 0;
    return card.getBoundingClientRect().width + gap;
  }
  function maxScroll(){ return track ? track.scrollWidth - track.clientWidth : 0; }
  function curIndex(){
    var s = step();
    return s ? Math.round(track.scrollLeft / s) : 0;
  }
  function buildDots(){
    if(!track || !dotsWrap) return;
    var cards = track.children;
    dotsWrap.innerHTML = "";
    Array.prototype.forEach.call(cards, function(_, i){
      var b = document.createElement("button");
      b.className = "tsti-dot";
      b.type = "button";
      b.setAttribute("aria-label", "Go to testimony " + (i + 1));
      b.addEventListener("click", function(){
        track.scrollTo({ left: i * step(), behavior: "smooth" });
      });
      dotsWrap.appendChild(b);
    });
  }
  function sync(){
    if(!track || !dotsWrap) return;
    var i = curIndex();
    Array.prototype.forEach.call(dotsWrap.children, function(d, k){
      d.classList.toggle("is-on", k === i);
    });
    if(prevBtn) prevBtn.disabled = track.scrollLeft <= 2;
    if(nextBtn) nextBtn.disabled = track.scrollLeft >= maxScroll() - 2;
  }
  if(track){
    if(prevBtn) prevBtn.addEventListener("click", function(){ track.scrollBy({ left: -step(), behavior: "smooth" }); });
    if(nextBtn) nextBtn.addEventListener("click", function(){ track.scrollBy({ left: step(), behavior: "smooth" }); });
    var stmr;
    track.addEventListener("scroll", function(){ window.clearTimeout(stmr); stmr = window.setTimeout(sync, 80); });
    window.addEventListener("resize", function(){ buildDots(); sync(); });
    buildDots();
    sync();
  }

  /* ---- full testimony modal ---- */
  var modal = document.getElementById("tstiModal");
  var lastFocused = null;
  function openModal(tid){
    var d = TDATA[tid];
    if(!d || !modal) return;
    document.getElementById("tstiModalImg").src = d.img;
    document.getElementById("tstiModalImg").alt = d.name;
    document.getElementById("tstiModalName").textContent = d.name;
    document.getElementById("tstiModalTitle").textContent = d.title;
    var body = document.getElementById("tstiModalBody");
    body.innerHTML = "";
    (d.full || []).forEach(function(p){
      var el = document.createElement("p");
      el.textContent = p;
      body.appendChild(el);
    });
    document.getElementById("tstiModalSign").textContent = "\u2014 " + d.name;
    lastFocused = document.activeElement;
    modal.hidden = false;
    document.body.style.overflow = "hidden";
    modal.querySelector(".tsti-modal__scroll").scrollTop = 0;
  }
  function closeModal(){
    if(!modal) return;
    modal.hidden = true;
    document.body.style.overflow = "";
    if(lastFocused && lastFocused.focus) lastFocused.focus();
  }
  document.addEventListener("click", function(e){
    var more = e.target.closest && e.target.closest(".tsti-card__more");
    if(more){ openModal(more.getAttribute("data-tid")); return; }
    if(e.target.closest && e.target.closest("[data-close]")){ closeModal(); }
  });
  document.addEventListener("keydown", function(e){
    if(e.key === "Escape" && modal && !modal.hidden) closeModal();
  });
